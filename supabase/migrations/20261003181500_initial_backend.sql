create policy organizations_select_members
on public.organizations for select to authenticated
using (id in (select private.user_organization_ids()));

create policy organizations_update_admins
on public.organizations for update to authenticated
using ((select private.user_has_organization_role(id, array['owner', 'admin']::public.organization_role[])))
with check ((select private.user_has_organization_role(id, array['owner', 'admin']::public.organization_role[])));

create policy organization_members_select_members
on public.organization_members for select to authenticated
using (organization_id in (select private.user_organization_ids()));

create policy organization_members_manage_admins
on public.organization_members for all to authenticated
using ((select private.user_has_organization_role(organization_id, array['owner', 'admin']::public.organization_role[])))
with check ((select private.user_has_organization_role(organization_id, array['owner', 'admin']::public.organization_role[])));

create policy documents_select_members
on public.documents for select to authenticated
using (organization_id in (select private.user_organization_ids()));

create policy documents_insert_members
on public.documents for insert to authenticated
with check (
  organization_id in (select private.user_organization_ids())
  and uploaded_by = (select auth.uid())
);

create policy documents_update_reviewers
on public.documents for update to authenticated
using ((select private.user_has_organization_role(organization_id, array['owner', 'admin', 'accountant', 'reviewer']::public.organization_role[])))
with check ((select private.user_has_organization_role(organization_id, array['owner', 'admin', 'accountant', 'reviewer']::public.organization_role[])));

create policy document_extractions_select_members
on public.document_extractions for select to authenticated
using (
  exists (
    select 1 from public.documents
    where documents.id = document_extractions.document_id
      and documents.organization_id in (select private.user_organization_ids())
  )
);

create policy ledger_entries_select_members
on public.ledger_entries for select to authenticated
using (organization_id in (select private.user_organization_ids()));

create policy ledger_entries_insert_accountants
on public.ledger_entries for insert to authenticated
with check (
  (select private.user_has_organization_role(organization_id, array['owner', 'admin', 'accountant']::public.organization_role[]))
  and created_by = (select auth.uid())
);

create policy ledger_entries_update_accountants
on public.ledger_entries for update to authenticated
using ((select private.user_has_organization_role(organization_id, array['owner', 'admin', 'accountant']::public.organization_role[])))
with check ((select private.user_has_organization_role(organization_id, array['owner', 'admin', 'accountant']::public.organization_role[])));

create policy ledger_lines_select_members
on public.ledger_lines for select to authenticated
using (
  exists (
    select 1 from public.ledger_entries
    where ledger_entries.id = ledger_lines.entry_id
      and ledger_entries.organization_id in (select private.user_organization_ids())
  )
);

create policy ledger_lines_write_accountants
on public.ledger_lines for all to authenticated
using (
  exists (
    select 1 from public.ledger_entries
    where ledger_entries.id = ledger_lines.entry_id
      and (select private.user_has_organization_role(ledger_entries.organization_id, array['owner', 'admin', 'accountant']::public.organization_role[]))
  )
)
with check (
  exists (
    select 1 from public.ledger_entries
    where ledger_entries.id = ledger_lines.entry_id
      and (select private.user_has_organization_role(ledger_entries.organization_id, array['owner', 'admin', 'accountant']::public.organization_role[]))
  )
);

create policy audit_events_select_members
on public.audit_events for select to authenticated
using (organization_id in (select private.user_organization_ids()));

